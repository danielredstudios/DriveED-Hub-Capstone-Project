import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {execFileSync} from 'node:child_process';

const output='tmp/nov1-findings';
await fs.mkdir(output,{recursive:true});
const browser=await puppeteer.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--no-sandbox'],defaultViewport:{width:1440,height:1000}});
const errors=[];
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const report=message=>console.log('PASS: '+message);
let original;
let admin;
execFileSync('docker',['exec','driveed_hub_app','php','tests/nov1-package-snapshot.php','save']);
const save=async data=>admin.evaluate(async data=>{
 const form=new FormData();
 form.set('_token',document.querySelector('meta[name="csrf-token"]').content);
 form.set('_method','PUT');
 for(const key of ['name','vehicle_category_id','transmission_type','price','tdc_hours','pdc_hours','description']) form.set(key,data[key]??'');
 if(data.is_popular)form.set('is_popular','1');
 for(const feature of data.features??[])form.append('features[]',feature);
 const response=await fetch(`/drived-hub/admin/courses/${data.course_id}/packages/${data.id}`,{method:'POST',body:form});
 return response.status;
},data);
try {
 const login=async role=>{
  const context=await browser.createBrowserContext();
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:8004/drived-hub/login',{waitUntil:'networkidle2'});
  await page.type('[name=email]',role+(role==='guest'?'6':'1')+'@driveedhub.test');
  await page.type('[name=password]','DriveDemo123');
  await Promise.all([page.waitForNavigation({waitUntil:'networkidle2'}),page.click('button[type=submit]')]);
  return page;
 };
 admin=await login('admin');
 await admin.goto('http://localhost:8004/drived-hub/admin/courses',{waitUntil:'networkidle2'});
 original=await admin.evaluate(()=>coursesData.find(c=>c.id===1).packages[0]);
 const edited={...original,name:'Nov 1 package "updated"',price:'2301.00',description:'Saved description <with text>',features:['','Feature "three"']};
 await admin.evaluate((pkg)=>{openPackageModal(pkg.course_id,pkg.id);document.getElementById('packageName').value=pkg.name;document.getElementById('packagePrice').value=pkg.price;document.getElementById('packageDescription').value=pkg.description;document.getElementById('packageFeaturesContainer').innerHTML='';pkg.features.forEach(addPackageFeature);},edited);
 await admin.click('#packageForm button[type=submit]');
 await admin.waitForFunction(name=>coursesData.find(c=>c.id===1).packages[0].name===name,{},edited.name);
 await admin.evaluate(pkg=>openPackageModal(pkg.course_id,pkg.id),original);
 assert.equal(await admin.$eval('#packageName',el=>el.value),edited.name);
 assert.equal(await admin.$eval('#packagePrice',el=>Number(el.value)),2301);
 assert.equal(await admin.$eval('#packageDescription',el=>el.value),edited.description);
 assert.deepEqual(await admin.$$eval('#packageFeaturesContainer input',els=>els.map(el=>el.value)),['Feature "three"']);
 report('Actual modal save refreshes admin data; Edit restores name, price, description, and filtered quoted features');
 await admin.screenshot({path:output+'/package-edit-saved.png'});
 await admin.evaluate(()=>{closePackageModal();openPreviewModal(1)});
 assert((await admin.$eval('#previewContent',el=>el.innerText)).includes(edited.name));
 assert((await admin.$eval('#previewContent',el=>el.innerText)).includes(edited.description));
 assert.equal(await admin.$$eval('#previewContent .enroll-package-detail',els=>els.length),1);
 await admin.screenshot({path:output+'/admin-preview-desktop.png'});
 await admin.setViewport({width:390,height:844});
 await admin.screenshot({path:output+'/admin-preview-mobile.png'});
 assert(await admin.$eval('#previewModal .modal-content',el=>el.getBoundingClientRect().width<=innerWidth));
 report('Preview uses saved enrollment package details and fits desktop/mobile');
 await admin.setViewport({width:1440,height:1000});
 await admin.evaluate(()=>{closePreviewModal();loadContent('/drived-hub/admin/courses')});
 await admin.waitForFunction(()=>document.querySelector('.packages-ticker-container')?.dataset.tickerReady==='1');
 await pause(700);
 assert.equal(errors.length,0,errors.join('\n'));
 await admin.evaluate(()=>{
  const container=document.querySelector('.packages-ticker-container');
  const ticker=container.querySelector('.packages-ticker');
  for(let n=0;n<4;n++)ticker.append(ticker.firstElementChild.cloneNode(true));
  delete container.dataset.tickerReady;
  container.id='tickerUnderTest';
  initPackageTickers();
 });
 await admin.$eval('#tickerUnderTest',el=>el.scrollIntoView({block:'center'}));
 await admin.mouse.move(0,0);
 const before=await admin.$eval('#tickerUnderTest',el=>el.scrollTop);
 await pause(850);
 const moving=await admin.$eval('#tickerUnderTest',el=>el.scrollTop);
 assert(moving>before);
 await admin.hover('#tickerUnderTest');
 await pause(100);
 const stopped=await admin.$eval('#tickerUnderTest',el=>el.scrollTop);
 await pause(450);
 assert.equal(await admin.$eval('#tickerUnderTest',el=>el.scrollTop),stopped);
 await admin.mouse.wheel({deltaY:80});
 await pause(250);
 const manual=await admin.$eval('#tickerUnderTest',el=>el.scrollTop);
 assert(manual>stopped);
 await admin.screenshot({path:output+'/packages-manual-scroll.png'});
 await admin.mouse.move(0,0);
 await pause(600);
 assert((await admin.$eval('#tickerUnderTest',el=>el.scrollTop))>manual);
 await admin.emulateMediaFeatures([{name:'prefers-reduced-motion',value:'reduce'}]);
 await pause(100);
 const reduced=await admin.$eval('#tickerUnderTest',el=>el.scrollTop);
 await pause(300);
 assert.equal(await admin.$eval('#tickerUnderTest',el=>el.scrollTop),reduced);
 report('Four-plus packages scroll automatically, pause on hover, accept wheel scrolling, resume on leave, and respect reduced motion');
 const guest=await login('guest');
 await guest.goto('http://localhost:8004/drived-hub/guest/courses',{waitUntil:'networkidle2'});
 const select='#experience_level2';
 assert(await guest.$(select));
 assert((await guest.$$eval(select+' option',els=>els.map(el=>el.textContent))).some(text=>text.includes("New Driver (Have Student Driver's License)")));
 await guest.select(select,'experienced');
 assert.equal(await guest.$eval('#licenseLabel2',el=>el.textContent),"Driver's License");
 await guest.evaluate(()=>{const modal=document.getElementById('experience_level2').closest('.modal');modal.style.display='block';modal.classList.add('show');document.getElementById('experience_level2').scrollIntoView({block:'start'});});
 await guest.screenshot({path:output+'/guest-experienced-license.png'});
 await guest.select(select,'new_driver_with_license');
 assert.equal(await guest.$eval('#licenseLabel2',el=>el.textContent),"Student Driver's License");
 await guest.screenshot({path:output+'/guest-new-driver-license.png'});
 report('Guest practical enrollment includes new drivers with student licenses and switches the license label for experienced drivers');
 const student=await login('student');
 await student.goto('http://localhost:8004/drived-hub/student/courses/2',{waitUntil:'networkidle2'});
 await student.select('#exp_level','experienced');
 const label=await student.$('#studentLicenseLabel');
 if(label)assert.equal(await label.evaluate(el=>el.textContent),"Upload Driver's License");
 await student.select('#exp_level','new_driver_with_license');
 if(label)assert.equal(await label.evaluate(el=>el.textContent),"Upload Student Driver's License");
 await student.evaluate(()=>{openEnrollModal();document.getElementById('exp_level').scrollIntoView({block:'center'});});
 await student.screenshot({path:output+'/student-new-driver-license.png'});
 report('Student enrollment offers both license-holder experience levels');
 assert.deepEqual(errors,[]);
} finally {
 if(original&&admin)assert.equal(await save(original),200,'Restore original package');
 execFileSync('docker',['exec','driveed_hub_app','php','tests/nov1-package-snapshot.php','restore']);
 await browser.close();
}
